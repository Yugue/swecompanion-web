import type Stripe from "stripe";
import type { SubscriptionSummary } from "./shared/billing";

export interface PassEntitlement {
  checkoutId: string;
  /** Older nonrenewing passes may not contain this field. */
  customerId?: string;
  startsAt: number;
  expiresAt: number;
  amount: number;
  currency: string;
  revoked: boolean;
}

export interface PassPurchase {
  checkoutId: string;
  customerId: string;
  uid: string;
  priceId: string;
  amount: number;
  currency: string;
  months: number;
}

/** Calendar months, clamped to the last day when the target month is shorter. */
export function addCalendarMonths(seconds: number, months: number): number {
  const date = new Date(seconds * 1000);
  const day = date.getUTCDate();
  date.setUTCDate(1);
  date.setUTCMonth(date.getUTCMonth() + months);
  const lastDay = new Date(Date.UTC(date.getUTCFullYear(), date.getUTCMonth() + 1, 0)).getUTCDate();
  date.setUTCDate(Math.min(day, lastDay));
  return Math.floor(date.getTime() / 1000);
}

/** Inputs come from Stripe and a server-owned checkout record, never browser fields. */
export function paidPass(
  purchase: PassPurchase, session: Stripe.Checkout.Session, items: Stripe.LineItem[], charge: Stripe.Charge | null,
): PassEntitlement | null {
  const customer = typeof session.customer === "string" ? session.customer : session.customer?.id;
  const item = items[0];
  const intent = typeof session.payment_intent === "string" ? session.payment_intent : session.payment_intent?.id;
  const chargeIntent = typeof charge?.payment_intent === "string" ? charge.payment_intent : charge?.payment_intent?.id;
  const chargeCustomer = typeof charge?.customer === "string" ? charge.customer : charge?.customer?.id;
  // Stripe reports Adaptive Pricing totals in the original integration currency.
  // Validate its computed discount against the locked catalog subtotal, not a browser-supplied total.
  const discount = session.total_details?.amount_discount;
  const total = session.amount_total;
  if (session.id !== purchase.checkoutId || session.mode !== "payment" || session.livemode ||
    session.status !== "complete" || customer !== purchase.customerId ||
    session.client_reference_id !== purchase.uid || session.metadata?.plan !== "threeMonthPass" ||
    items.length !== 1 || item.quantity !== 1 || item.price?.id !== purchase.priceId || item.price.recurring ||
    item.price.unit_amount !== purchase.amount || item.price.currency !== purchase.currency ||
    session.amount_subtotal !== purchase.amount || session.currency !== purchase.currency ||
    !Number.isSafeInteger(discount) || discount! < 0 || discount! > purchase.amount ||
    !Number.isSafeInteger(total) || total !== purchase.amount - discount! ||
    session.total_details?.amount_tax !== 0 || session.total_details.amount_shipping !== 0 ||
    item.amount_subtotal !== purchase.amount || item.amount_discount !== discount ||
    item.amount_total !== total || item.amount_tax !== 0 || item.currency !== purchase.currency ||
    purchase.months !== 3) return null;
  let startsAt: number;
  if (total === 0) {
    // A 100% Stripe promotion has no charge. Require the paid invoice generated by this Checkout.
    const invoice = session.invoice && typeof session.invoice !== "string" ? session.invoice : null;
    const invoiceCustomer = typeof invoice?.customer === "string" ? invoice.customer : invoice?.customer?.id;
    const paidAt = invoice?.status_transitions.paid_at;
    if (!["paid", "no_payment_required"].includes(session.payment_status) || intent || charge || !invoice || invoice.livemode ||
      invoice.status !== "paid" || invoiceCustomer !== purchase.customerId || invoice.amount_paid !== 0 ||
      invoice.total !== 0 || invoice.currency !== purchase.currency || !paidAt || !Number.isFinite(paidAt)) return null;
    startsAt = paidAt;
  } else {
    if (session.payment_status !== "paid" || !charge || charge.livemode || !charge.paid || charge.status !== "succeeded" ||
      !intent || chargeIntent !== intent || chargeCustomer !== purchase.customerId ||
      charge.amount !== total || charge.currency !== purchase.currency || !Number.isFinite(charge.created)) return null;
    startsAt = charge.created;
  }
  return {
    checkoutId: session.id, customerId: purchase.customerId, startsAt, expiresAt: addCalendarMonths(startsAt, purchase.months),
    amount: total!, currency: purchase.currency, revoked: Boolean(charge?.refunded || charge?.disputed),
  };
}

export function passSummary(pass: PassEntitlement, now = Date.now() / 1000): Omit<SubscriptionSummary, "claimsVersion"> {
  const subscribed = !pass.revoked && pass.startsAt <= now && pass.expiresAt > now;
  return {
    subscribed, status: subscribed ? "active" : "canceled", plan: "threeMonthPass",
    currentPeriodEnd: pass.expiresAt, billingCycleAnchor: pass.startsAt,
    cancelAtPeriodEnd: true, amount: pass.amount, currency: pass.currency,
  };
}
