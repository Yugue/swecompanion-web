/** Whole-corpus editorial signals. These identify review work; they do not certify pedagogy. */
import assert from "node:assert/strict";
import fs from "node:fs";
import katex from "katex";
import { lessonCurricula, type CurriculumPart } from "../src/lib/lessonCurricula";
import { getLessonBlocks, type LessonTrack } from "../src/lib/getLessonBlocks";
import { parseInline } from "../src/lib/lessonParser";

const write = process.argv.includes("--write");
const passages = new Map<string, Set<string>>();
const inventory: {
  track: LessonTrack; id: string; title: string; chapter: string; words: number;
  sections: number; figures: number; diagrams: number; tables: number; formulas: number;
  longParagraphs: number; exampleCue: boolean; recordedPrerequisites: string[];
}[] = [];
for (const track of Object.keys(lessonCurricula) as LessonTrack[]) {
  const parts: readonly CurriculumPart[] = lessonCurricula[track];
  const topics = parts.flatMap(part => part.topics);
  assert.equal(new Set(topics.map(topic => topic.id)).size, topics.length, `${track}: repeated topic ID`);
  assert.deepEqual(fs.readdirSync(`src/content/${track}-lessons`).filter(file => file.endsWith(".md")).sort(), topics.map(topic => `${topic.id}.md`).sort());
  const seen = new Set<string>();
  for (const part of parts) {
    for (const topic of part.topics) {
      const key = `${track}/${topic.id}`;
      const source = fs.readFileSync(`src/content/${track}-lessons/${topic.id}.md`, "utf8");
      assert.equal((source.match(/^```/gm) ?? []).length % 2, 0, `${key}: unclosed fence`);
      assert.doesNotMatch(source, /\b(?:TODO|TBD|coming soon)\b/i, key);
      const blocks = getLessonBlocks(topic.id, track);
      for (const block of blocks) {
        if (block.type === "math") katex.renderToString(block.text, { throwOnError: true });
        if (["paragraph", "quote", "bullet", "numbered", "table"].includes(block.type)) {
          for (const token of parseInline(block.text)) if (token.kind === "math") katex.renderToString(token.text, { throwOnError: true });
        }
        if (["paragraph", "quote"].includes(block.type) && block.text.trim().split(/\s+/).length >= 20) {
          const normalized = block.text.toLowerCase().replace(/\s+/g, " ").trim();
          const owners = passages.get(normalized) ?? new Set<string>();
          owners.add(key); passages.set(normalized, owners);
        }
      }
      const explicit = topic.prerequisites;
      for (const id of explicit ?? []) assert.ok(seen.has(id), `${key}: prerequisite ${id} must exist earlier in its curriculum`);
      inventory.push({
        track, id: topic.id, title: topic.title, chapter: part.title,
        words: source.trim().split(/\s+/).length,
        sections: blocks.filter(block => /heading[123]/.test(block.type)).length,
        figures: blocks.filter(block => /visual/.test(block.type)).length,
        diagrams: blocks.filter(block => block.type === "diagram").length,
        tables: blocks.filter(block => block.type === "table").length,
        formulas: blocks.filter(block => block.type === "math").length,
        longParagraphs: blocks.filter(block => ["paragraph", "quote"].includes(block.type) && block.text.split(/\s+/).length > 85).length,
        exampleCue: /\b(?:example|suppose|consider|imagine|picture|take|e\.g\.)\b|\d+\s*[×=]/i.test(source),
        recordedPrerequisites: explicit ?? [],
      });
      seen.add(topic.id);
    }
  }
}
const duplicates = [...passages].filter(([, owners]) => owners.size > 1).map(([text, owners]) => ({ lessons: [...owners], text }));
const summaries = (Object.keys(lessonCurricula) as LessonTrack[]).map(track => {
  const rows = inventory.filter(row => row.track === track);
  return { track, lessons: rows.length, words: rows.reduce((sum, row) => sum + row.words, 0),
    min: Math.min(...rows.map(row => row.words)), max: Math.max(...rows.map(row => row.words)),
    longLessons: rows.filter(row => row.words > 750).length,
    longParagraphs: rows.reduce((sum, row) => sum + row.longParagraphs, 0),
    figures: rows.reduce((sum, row) => sum + row.figures, 0),
    recordedDependencies: rows.filter(row => row.recordedPrerequisites.length > 0).length };
});
if (write) {
  fs.writeFileSync("docs/ml-content-inventory.json", JSON.stringify({ counting: "Whitespace-delimited source words, including notation and code; duplicate prose blocks of at least 20 words; example cues are heuristic, not a quality score.", summaries, inventory, duplicates }, null, 2) + "\n");
  const lines = ["# ML content review queue", "", "Generated by `npx tsx scripts/auditMlContent.ts --write`. Signals locate review work; they do not establish factual correctness, missing prerequisites, or visual usefulness. Read alongside [the editorial audit](ml-content-audit.md).", "", "| Domain | Lesson | Source words | Teaching aids¹ | Review signals |", "|---|---|---:|---|---|"];
  for (const row of inventory) {
    const key = `${row.track}/${row.id}`;
    const repeated = duplicates.filter(item => item.lessons.includes(key));
    const flags = [row.words > 750 ? "Length review" : "", row.longParagraphs ? `${row.longParagraphs} long paragraphs` : "", repeated.length ? `${repeated.length} shared passages` : "", !row.exampleCue ? "Check concrete example" : "", !row.figures && !row.diagrams && !row.tables ? "Consider a teaching aid" : ""].filter(Boolean);
    lines.push(`| ${row.track} | [${row.title.replaceAll("|", "\\|")}](../src/content/${row.track}-lessons/${row.id}.md) | ${row.words} | ${row.figures} / ${row.diagrams} / ${row.tables} | ${flags.join("; ") || "No mechanical flag; editorial judgment still required"} |`);
  }
  lines.push("", "¹ Teaching aids: registered figures / text diagrams / tables. Equations are counted separately in the JSON inventory. The absence of a figure is not a defect when prose or an example explains the topic adequately.", "", "## Shared passages", "", "These are candidates for canonical ownership, not instructions to replace clear definitions with synonyms. Short prerequisite refreshers may appropriately recur.", "");
  for (const item of duplicates) lines.push(`- ${item.lessons.join(" ↔ ")}: ${item.text.slice(0, 180).replaceAll("\n", " ")}…`);
  fs.writeFileSync("docs/ml-content-review-queue.md", lines.join("\n").trimEnd() + "\n");
}
console.log(JSON.stringify({ lessons: inventory.length, summaries, duplicatePassages: duplicates.length }, null, 2));
